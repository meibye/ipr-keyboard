#!/usr/bin/env bash
#
# 07_show_info.sh
#
# Purpose:
#   Display the most important information the user needs after provisioning:
#   hotspot SSID and password, web dashboard URL, SSH access, and Bluetooth name.
#
#   Hotspot credentials are read from /etc/ipr-hotspot.secret (written by
#   04_enable_services.sh or ipr-provision.sh on first run).  Run this script
#   at any time to display the current credentials.
#
# Usage:
#   sudo ./provision/07_show_info.sh                  # passwords only on a terminal
#   sudo ./provision/07_show_info.sh --show-secrets   # always print them
#   sudo ./provision/07_show_info.sh --hide-secrets   # never print them
#
# The passwords (hotspot / setup portal, first dashboard login) are printed
# only when stdout is a terminal.  Piped or redirected -- the provisioning
# wizard tees everything into /opt/ipr_state/provision_wizard.log, and after a
# reboot it runs as a service whose output lands in the journal -- they are
# replaced by a pointer to /opt/ipr_state/credentials.txt (root only), which
# always gets them.  An install once left them in a log any user could read.
#
# Prerequisites:
#   - /opt/ipr_common.env (populated by earlier provisioning steps)
#
# category: Provisioning
# purpose: Display post-provisioning summary (credentials, URLs, SSH access)
# sudo: recommended

set -euo pipefail

if [[ "$(id -u)" -ne 0 ]]; then
  echo "Error: this script must be run as root. Use: sudo $0" >&2
  exit 1
fi

SHOW_SECRETS=""
for arg in "$@"; do
  case "$arg" in
    --show-secrets) SHOW_SECRETS=1 ;;
    --hide-secrets) SHOW_SECRETS=0 ;;
    *) echo "usage: $0 [--show-secrets|--hide-secrets]" >&2; exit 2 ;;
  esac
done
if [[ -z "$SHOW_SECRETS" ]]; then
  [[ -t 1 ]] && SHOW_SECRETS=1 || SHOW_SECRETS=0
fi

BOLD='\033[1m'
GREEN='\033[0;32m'
BLUE='\033[1;34m'
CYAN='\033[0;36m'
YELLOW='\033[1;33m'
NC='\033[0m'

# The locations can be overridden for tests; the defaults are the device's.
CRED_FILE="${IPR_CREDENTIALS_FILE:-/opt/ipr_state/credentials.txt}"

# A password, or -- off a terminal -- where to find it.
secret() {
  if [[ "$SHOW_SECRETS" == 1 ]]; then
    printf '%s' "$1"
  else
    printf '(in %s: sudo cat it)' "$CRED_FILE"
  fi
}

# Load environment (best-effort)
ENV_FILE="${IPR_COMMON_ENV:-/opt/ipr_common.env}"
if [[ -f "$ENV_FILE" ]]; then
  # shellcheck disable=SC1090
  source "$ENV_FILE"
fi

BT_DEVICE_NAME="${BT_DEVICE_NAME:-IPR Keyboard}"
AP_SSID_PREFIX="${AP_SSID_PREFIX:-ipr-setup}"
REPO_DIR="${REPO_DIR:-/home/meibye/dev/ipr-keyboard}"
APP_USER="${APP_USER:-meibye}"

# ── Hotspot credentials ───────────────────────────────────────────────────────
# Read from /etc/ipr-hotspot.secret (generated by ipr-provision.sh or
# 04_enable_services.sh).  Fall back gracefully if the file is absent.
SECRET_FILE="${IPR_HOTSPOT_SECRET:-/etc/ipr-hotspot.secret}"
HOTSPOT_SSID=""
HOTSPOT_PASS=""
if [[ -f "$SECRET_FILE" ]]; then
  HOTSPOT_SSID=$(grep '^SSID=' "$SECRET_FILE" | cut -d= -f2-)
  HOTSPOT_PASS=$(grep '^PASS=' "$SECRET_FILE" | cut -d= -f2-)
fi
if [[ -z "$HOTSPOT_SSID" ]]; then
  HOTSPOT_SSID="(not yet generated — run ipr-provision.sh first)"
fi
if [[ -z "$HOTSPOT_PASS" ]]; then
  HOTSPOT_PASS="(not yet generated — run ipr-provision.sh first)"
fi

# ── Network ───────────────────────────────────────────────────────────────────
DEVICE_HOSTNAME=$(hostname 2>/dev/null || echo "unknown")
MDNS_NAME="${DEVICE_HOSTNAME}.local"
CURRENT_IP=$(hostname -I 2>/dev/null | awk '{print $1}' || echo "")

# ── Dashboard port (read from config.json, fall back to default) ──────────────
DASHBOARD_PORT=8080
CONFIG_JSON="${REPO_DIR}/config.json"
if [[ -f "$CONFIG_JSON" ]] && command -v python3 &>/dev/null; then
  DASHBOARD_PORT=$(python3 -c \
    "import json; d=json.load(open('${CONFIG_JSON}')); print(d.get('LogPort', 8080))" \
    2>/dev/null || echo 8080)
fi

# The dashboard serves HTTPS; drop the port suffix on the standard 443.
_PORT_SUFFIX=":${DASHBOARD_PORT}"
[[ "$DASHBOARD_PORT" == "443" ]] && _PORT_SUFFIX=""
if [[ -n "$CURRENT_IP" ]]; then
  DASHBOARD_URL="https://${CURRENT_IP}${_PORT_SUFFIX}/"
else
  DASHBOARD_URL="https://<device-ip>${_PORT_SUFFIX}/"
fi
DASHBOARD_MDNS_URL="https://${MDNS_NAME}${_PORT_SUFFIX}/"

# Initial admin password — written by the app on first start, removed when
# the admin password is changed in the dashboard.
ADMIN_PWD_FILE="${REPO_DIR}/admin_initial_password.txt"
ADMIN_INITIAL_PWD=""
[[ -r "$ADMIN_PWD_FILE" ]] && ADMIN_INITIAL_PWD="$(tr -d '\r\n' < "$ADMIN_PWD_FILE")"

# ── Print summary ─────────────────────────────────────────────────────────────
echo ""
echo -e "${BLUE}${BOLD}╔══════════════════════════════════════════════════╗${NC}"
echo -e "${BLUE}${BOLD}║         IPR Keyboard — Device Information        ║${NC}"
echo -e "${BLUE}${BOLD}╚══════════════════════════════════════════════════╝${NC}"
echo ""

echo -e "${CYAN}${BOLD}── Bluetooth ──────────────────────────────────────────${NC}"
echo -e "  Device name  : ${BOLD}${BT_DEVICE_NAME}${NC}"
echo -e "  Pairing      : Search for '${BT_DEVICE_NAME}' on the host device"
echo ""

echo -e "${CYAN}${BOLD}── Wi-Fi Management Hotspot (on demand: magnet menu) ──${NC}"
echo -e "  SSID         : ${BOLD}${HOTSPOT_SSID}${NC}"
echo -e "  Password     : ${BOLD}$(secret "$HOTSPOT_PASS")${NC}"
echo -e "  Setup URL    : ${BOLD}https://10.42.0.1/setup/${NC}"
echo -e "  Web UI login : ${BOLD}ipr${NC} / the hotspot password"
echo ""

echo -e "${CYAN}${BOLD}── Web Dashboard ──────────────────────────────────────${NC}"
echo -e "  By IP        : ${BOLD}${DASHBOARD_URL}${NC}"
echo -e "  By mDNS      : ${BOLD}${DASHBOARD_MDNS_URL}${NC}"
if [[ -n "$ADMIN_INITIAL_PWD" ]]; then
  echo -e "  Login        : ${BOLD}admin${NC} / ${BOLD}$(secret "$ADMIN_INITIAL_PWD")${NC}"
  echo -e "                 (initial password — change it in the dashboard; this line"
  echo -e "                  and admin_initial_password.txt then disappear)"
elif [[ -f "${REPO_DIR}/users.json" ]]; then
  echo -e "  Login        : ${BOLD}admin${NC} / the password set in the dashboard"
else
  echo -e "  Login        : admin / generated at first start of ipr_keyboard.service"
  echo -e "                 (re-run this script, or see the setup portal home page)"
fi
echo ""

echo -e "${CYAN}${BOLD}── SSH Access ─────────────────────────────────────────${NC}"
if [[ -n "$CURRENT_IP" ]]; then
  echo -e "  By IP        : ${BOLD}ssh ${APP_USER}@${CURRENT_IP}${NC}"
fi
echo -e "  By mDNS      : ${BOLD}ssh ${APP_USER}@${MDNS_NAME}${NC}"
echo ""

echo -e "${CYAN}${BOLD}── Device ─────────────────────────────────────────────${NC}"
echo -e "  Hostname     : ${BOLD}${DEVICE_HOSTNAME}${NC}"
echo ""

echo -e "${GREEN}${BOLD}Provisioning complete. Device is ready for use.${NC}"
echo ""

# ── Keep the credentials ──────────────────────────────────────────────────────
#
# Everything above used to exist only in the terminal that ran provisioning.
# An unattended install has no such terminal, and after a factory reset the
# hotspot key is the only way back onto a device with no Wi-Fi -- which is
# exactly when the scrollback is long gone.  Write them where root can find
# them again.  0600 and root-owned: this file is a password store.
if mkdir -p "$(dirname "$CRED_FILE")" 2>/dev/null; then
  # umask 077 in the subshell: the file is never readable by others, not
  # even for the moment between creating it and a chmod.
  ( umask 077; {
    echo "# IPR Keyboard credentials"
    echo "# Written by provision/07_show_info.sh on $(date -Is)"
    echo "# Regenerated by every provisioning run.  Root-only on purpose."
    echo ""
    echo "hostname              = ${DEVICE_HOSTNAME}"
    echo "bluetooth_name        = ${BT_DEVICE_NAME}"
    echo ""
    echo "hotspot_ssid          = ${HOTSPOT_SSID}"
    echo "hotspot_password      = ${HOTSPOT_PASS}"
    echo "setup_portal          = https://10.42.0.1/setup/"
    echo "setup_login           = ipr / ${HOTSPOT_PASS}"
    echo ""
    echo "dashboard             = ${DASHBOARD_URL:-${DASHBOARD_MDNS_URL}}"
    echo "dashboard_mdns        = ${DASHBOARD_MDNS_URL}"
    echo "dashboard_admin       = admin / ${ADMIN_INITIAL_PWD:-(already changed)}"
    echo ""
    echo "# The hotspot key is also obtainable at the device itself:"
    echo "#   magnet menu -> Recovery info -> confirm with one tap"
    echo "# It is shown at most RecoveryRevealLimit times, and never once it"
    echo "# has been used to log in to the setup portal."
  } > "$CRED_FILE" ) 2>/dev/null \
    && chmod 0600 "$CRED_FILE" 2>/dev/null \
    && echo -e "${CYAN}  Credentials saved to ${BOLD}${CRED_FILE}${NC}${CYAN} (root only)${NC}" \
    || echo -e "${YELLOW}  Could not write ${CRED_FILE} -- note the values above${NC}"
  echo ""
fi
